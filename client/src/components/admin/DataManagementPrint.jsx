/* eslint-disable react/prop-types */
import { forwardRef } from "react";
import Regions from "../../assets/data/regions.json";
import { formatSelfReportPrintDate } from "../../utils/selfReportPrintHelpers";

const languageLabels = {
    en: "English", fil: "Filipino", ceb: "Cebuano",
    hil: "Hiligaynon", ilo: "Ilocano",
};

const DataManagementPrint = forwardRef(function DataManagementPrint({ report }, ref) {
    const { entries = [], filters = {}, generatedAt, generatedBy } = report || {};
    const isDatasetReport = report?.sourceType === "social_media";
    const itemLabel = isDatasetReport ? "datasets" : "reports";
    const headings = isDatasetReport
        ? ["File Name", "Records", "Languages", "Date Uploaded", "Uploaded by", "Status"]
        : ["Report ID", "Language", "Text", "Location", "Date Reported", "Status"];
    const columnWidths = isDatasetReport ? [30, 8, 16, 16, 20, 10] : [12, 9, 33, 23, 13, 10];
    const regionLabel = filters.region === "all" || !filters.region
        ? "All Regions"
        : Regions.regions.find(({ value }) => value === filters.region)?.label || filters.region;

    return (
        <article ref={ref} className="data-management-print">
            <style>{`
                .data-management-print, .data-management-print * {
                    box-sizing: border-box;
                    font-family: Arial, sans-serif;
                    color: #111827;
                }
                .data-management-print { font-size: 10px; line-height: 1.4; }
                .data-management-print h1 { margin: 0 0 4px; font-size: 20px; font-weight: 700; }
                .data-management-print p { margin: 0 0 4px; }
                .data-management-print .report-meta { margin: 12px 0 16px; }
                .data-management-print dl { display: grid; grid-template-columns: repeat(2, minmax(0, 1fr)); gap: 4px 20px; margin: 8px 0; }
                .data-management-print dl div { overflow-wrap: anywhere; }
                .data-management-print dt, .data-management-print dd { display: inline; margin: 0; }
                .data-management-print dt { font-weight: 700; }
                .data-management-print table { width: 100%; border-collapse: collapse; table-layout: fixed; font-size: 10px; }
                .data-management-print thead { display: table-header-group; }
                .data-management-print tr { break-inside: avoid; page-break-inside: avoid; }
                .data-management-print th, .data-management-print td { padding: 7px; border: 1px solid #d1d5db; text-align: left; vertical-align: top; overflow-wrap: anywhere; white-space: pre-wrap; }
                .data-management-print th { font-weight: 700; background: #f3f4f6; }
            `}</style>
            <header>
                <h1>HealthPH+ — {isDatasetReport ? "Social Media Datasets" : "Self Reports"}</h1>
                <p>Model Access and Toolkit · Data Management</p>
            </header>
            <div className="report-meta">
                <p>Generated: {formatSelfReportPrintDate(generatedAt)} PHT</p>
                <p>Generated by: {generatedBy || "Unavailable"}</p>
                <dl>
                    <div><dt>{isDatasetReport ? "Date uploaded: " : "Date reported: "}</dt><dd>{filters.dateFrom || "Any start date"} to {filters.dateTo || "Any end date"}</dd></div>
                    {!isDatasetReport && <div><dt>Region: </dt><dd>{regionLabel}</dd></div>}
                    <div><dt>Language: </dt><dd>{languageLabels[filters.language] || (filters.language === "all" || !filters.language ? "All Languages" : filters.language)}</dd></div>
                    <div><dt>Status: </dt><dd>{filters.analysisStatus === "all" || !filters.analysisStatus ? "All Status" : filters.analysisStatus}</dd></div>
                    <div><dt>Search: </dt><dd>{filters.search || "None"}</dd></div>
                </dl>
                <p><strong>Total matching {itemLabel}: {entries.length.toLocaleString()}</strong></p>
                <p>Includes all matching {itemLabel} across table pages. Dates and times use Philippine time (UTC+8).</p>
            </div>
            <table>
                <colgroup>
                    {columnWidths.map((width, index) => <col key={index} style={{ width: `${width}%` }} />)}
                </colgroup>
                <thead>
                    <tr>{headings.map((label) => <th key={label} scope="col">{label}</th>)}</tr>
                </thead>
                <tbody>
                    {entries.map((entry) => (
                        <tr key={entry.id}>
                            {isDatasetReport ? (
                                <>
                                    <td>{entry.filename || "Unavailable"}</td>
                                    <td>{typeof entry.num_of_rows === "number" ? entry.num_of_rows.toLocaleString() : entry.num_of_rows ?? "Unavailable"}</td>
                                    <td>{entry.languages?.length > 0 ? entry.languages.map((code) => languageLabels[code] || code).join(", ") : "Unavailable"}</td>
                                </>
                            ) : (
                                <>
                                    <td>{entry.sourcePublicId || entry.source_id || entry.report_id || entry.id}</td>
                                    <td>{languageLabels[entry.language] || entry.language || "Unavailable"}</td>
                                    <td>{entry.text || "Unavailable"}</td>
                                    <td>{entry.location?.raw || entry.location?.city || entry.location?.province || entry.location?.region || "Unavailable"}</td>
                                </>
                            )}
                            <td>{formatSelfReportPrintDate(entry.created_at)}</td>
                            {isDatasetReport && <td>{entry.user_name || "Unavailable"}</td>}
                            <td>{isDatasetReport ? entry.dataset_status || "UNKNOWN" : entry.analysis_status || "SUBMITTED"}</td>
                        </tr>
                    ))}
                </tbody>
            </table>
        </article>
    );
});

export default DataManagementPrint;
