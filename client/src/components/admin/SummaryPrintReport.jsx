/* eslint-disable react/prop-types */
import { forwardRef } from "react";
import { formatSelfReportPrintDate } from "../../utils/selfReportPrintHelpers";

// Shared table-based layout for printable aggregate reports, without page limits.
const SummaryPrintReport = forwardRef(function SummaryPrintReport({ report }, ref) {
    if (!report) return null;

    return (
        <article ref={ref} className="summary-print-report">
            <style>{`
                .summary-print-report, .summary-print-report * {
                    box-sizing: border-box; font-family: Arial, sans-serif; color: #111827;
                }
                .summary-print-report { font-size: 10pt; line-height: 1.4; }
                .summary-print-report h1 { margin: 0 0 4px; font-size: 18pt; }
                .summary-print-report h2 { margin: 20px 0 6px; font-size: 12pt; break-after: avoid; }
                .summary-print-report p { margin: 0 0 6px; }
                .summary-print-report dl { margin: 12px 0; }
                .summary-print-report dl div { margin-bottom: 3px; overflow-wrap: anywhere; }
                .summary-print-report dt, .summary-print-report dd { display: inline; margin: 0; }
                .summary-print-report dt { font-weight: bold; }
                .summary-print-report table { width: 100%; border-collapse: collapse; table-layout: fixed; }
                .summary-print-report th, .summary-print-report td {
                    padding: 6px 8px; border: 1px solid #d1d5db; text-align: left;
                    vertical-align: top; overflow-wrap: anywhere;
                }
                .summary-print-report th { background: #f3f4f6; }
                .summary-print-report th:nth-child(n+2), .summary-print-report td:nth-child(n+2) { text-align: right; }
                .summary-print-report thead { display: table-header-group; }
                .summary-print-report tr { break-inside: avoid; page-break-inside: avoid; }
            `}</style>
            <header>
                <h1>HealthPH+ — {report.title}</h1>
                <p>{report.subtitle}</p>
                <p>Generated: {formatSelfReportPrintDate(report.generatedAt)} PHT</p>
                <p>Generated by: {report.generatedBy}</p>
            </header>
            <dl>
                {report.filters.map(({ label, value }) => (
                    <div key={label}><dt>{label}: </dt><dd>{value}</dd></div>
                ))}
            </dl>
            <p><strong>{report.totalLabel || "Matching processed reports"}: {report.totalReports.toLocaleString()}</strong></p>
            {report.notes.map((note) => <p key={note}>{note}</p>)}
            {report.sections.map(({ title, rows, countLabel = "Reports", shareLabel = "Percentage out of all reports", showShare = true }) => (
                <section key={title}>
                    <h2>{title}</h2>
                    <table>
                        <colgroup>
                            <col style={{ width: showShare ? "50%" : "75%" }} />
                            <col style={{ width: showShare ? "20%" : "25%" }} />
                            {showShare && <col style={{ width: "30%" }} />}
                        </colgroup>
                        <thead>
                            <tr><th scope="col">Item</th><th scope="col">{countLabel}</th>{showShare && <th scope="col">{shareLabel}</th>}</tr>
                        </thead>
                        <tbody>
                            {rows.length ? rows.map(({ label, count, share }) => (
                                <tr key={label}><td>{label}</td><td>{count.toLocaleString()}</td>{showShare && <td>{share}%</td>}</tr>
                            )) : <tr><td colSpan={showShare ? 3 : 2}>No matching results.</td></tr>}
                        </tbody>
                    </table>
                </section>
            ))}
        </article>
    );
});

export default SummaryPrintReport;
