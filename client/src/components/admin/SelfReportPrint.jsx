/* eslint-disable react/prop-types */
import { forwardRef } from "react";
import Regions from "../../assets/data/regions.json";
import { formatSelfReportPrintDate } from "../../utils/selfReportPrintHelpers";

const languageLabels = {
    en: "English", fil: "Filipino", ceb: "Cebuano",
    hil: "Hiligaynon", ilo: "Ilocano",
};

const SelfReportPrint = forwardRef(function SelfReportPrint({ report }, ref) {
    const { entries = [], filters = {}, generatedAt, generatedBy } = report || {};
    const regionLabel = filters.region === "all" || !filters.region
        ? "All Regions"
        : Regions.regions.find(({ value }) => value === filters.region)?.label || filters.region;

    return (
        <article ref={ref} className="self-report-print">
            <style>{`
                .self-report-print, .self-report-print * {
                    box-sizing: border-box;
                    font-family: Arial, sans-serif;
                    color: #111827;
                }
                .self-report-print { font-size: 10px; line-height: 1.4; }
                .self-report-print h1 { margin: 0 0 4px; font-size: 20px; font-weight: 700; }
                .self-report-print p { margin: 0 0 4px; }
                .self-report-print .report-meta { margin: 12px 0 16px; }
                .self-report-print dl { display: grid; grid-template-columns: repeat(2, minmax(0, 1fr)); gap: 4px 20px; margin: 8px 0; }
                .self-report-print dl div { overflow-wrap: anywhere; }
                .self-report-print dt, .self-report-print dd { display: inline; margin: 0; }
                .self-report-print dt { font-weight: 700; }
                .self-report-print table { width: 100%; border-collapse: collapse; table-layout: fixed; font-size: 10px; }
                .self-report-print thead { display: table-header-group; }
                .self-report-print tr { break-inside: avoid; page-break-inside: avoid; }
                .self-report-print th, .self-report-print td { padding: 7px; border: 1px solid #d1d5db; text-align: left; vertical-align: top; overflow-wrap: anywhere; white-space: pre-wrap; }
                .self-report-print th { font-weight: 700; background: #f3f4f6; }
            `}</style>
            <header>
                <h1>HealthPH+ — Self Reports</h1>
                <p>Model Access and Toolkit · Data Management</p>
            </header>
            <div className="report-meta">
                <p>Generated: {formatSelfReportPrintDate(generatedAt)} PHT</p>
                <p>Generated by: {generatedBy || "Unavailable"}</p>
                <dl>
                    <div><dt>Date reported: </dt><dd>{filters.dateFrom || "Any start date"} to {filters.dateTo || "Any end date"}</dd></div>
                    <div><dt>Region: </dt><dd>{regionLabel}</dd></div>
                    <div><dt>Language: </dt><dd>{languageLabels[filters.language] || (filters.language === "all" || !filters.language ? "All Languages" : filters.language)}</dd></div>
                    <div><dt>Status: </dt><dd>{filters.analysisStatus === "all" || !filters.analysisStatus ? "All Status" : filters.analysisStatus}</dd></div>
                    <div><dt>Search: </dt><dd>{filters.search || "None"}</dd></div>
                </dl>
                <p><strong>Total matching reports: {entries.length.toLocaleString()}</strong></p>
                <p>Includes all matching reports across table pages. Dates and times use Philippine time (UTC+8).</p>
            </div>
            <table>
                <colgroup>
                    {[12, 9, 33, 23, 13, 10].map((width, index) => <col key={index} style={{ width: `${width}%` }} />)}
                </colgroup>
                <thead>
                    <tr>{["Report ID", "Language", "Text", "Location", "Date Reported", "Status"].map((label) => <th key={label} scope="col">{label}</th>)}</tr>
                </thead>
                <tbody>
                    {entries.map((entry) => (
                        <tr key={entry.id}>
                            <td>{entry.sourcePublicId || entry.source_id || entry.report_id || entry.id}</td>
                            <td>{languageLabels[entry.language] || entry.language || "Unavailable"}</td>
                            <td>{entry.text || "Unavailable"}</td>
                            <td>{entry.location?.raw || entry.location?.city || entry.location?.province || entry.location?.region || "Unavailable"}</td>
                            <td>{formatSelfReportPrintDate(entry.created_at)}</td>
                            <td>{entry.analysis_status || "SUBMITTED"}</td>
                        </tr>
                    ))}
                </tbody>
            </table>
        </article>
    );
});

export default SelfReportPrint;
